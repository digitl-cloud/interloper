/**
 * Derive from the app what an extension's UI builds and type-checks against, into `dist/`:
 *
 * - `host/`: the declarations of `@interloper/host`, emitted from the app's `host.ts`
 *   with every file they reach. The app's `~` imports become relative, and the types
 *   Nuxt's auto-imports make global in the app (`globalThis.ComputedRef`) are imported
 *   from where they come from.
 *   `host/components.d.ts` declares the components it exports global, for templates.
 * - `host.json`: the module names the app shares and the components `@interloper/host` exports.
 * - `theme.css`: the app's Tailwind theme, Nuxt UI's mapping to the `--ui-*` tokens included.
 * - `ui/`: the component themes Nuxt UI generated for the app (`#build/ui/*`), from which its
 *   components type their `color`, `variant` and `size`.
 *
 * Reads the app's `.nuxt/`, so the app is prepared first (`nuxt prepare`, which `pnpm install` runs).
 * A declaration error in a file `@interloper/host` reaches fails the build; the rest of
 * the app is not part of the contract and may use names a declaration cannot carry.
 */
import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, isAbsolute, join, relative, resolve } from 'node:path'
import { SHARED_MODULES } from '../../app/app/extensions/shared/modules.ts'

const APP = resolve(import.meta.dirname, '../../app')
const NUXT = join(APP, '.nuxt')
const HOST = join(APP, 'app/extensions/shared/host.ts')
const DIST = resolve(import.meta.dirname, '../dist')
const WORK = join(DIST, '.emit')
const OUT = join(WORK, 'out')

/** The app's path aliases, `~` → `<app>/app`, as its generated tsconfig maps them. */
const ALIASES = aliases()

const SPECIFIER = /(from |import\()(['"])([^'"]+)\2/g
const GLOBAL = /globalThis\.(\w+)/g

if (!existsSync(join(NUXT, 'tsconfig.app.json')))
    throw new Error(`${NUXT} is missing: prepare the app first (pnpm install, or nuxt prepare in ${APP})`)

rmSync(DIST, { recursive: true, force: true })
mkdirSync(DIST, { recursive: true })
const HOST_EXPORTS = host()
writeFileSync(join(DIST, 'host.json'), `${JSON.stringify(HOST_EXPORTS, null, 2)}\n`)
writeFileSync(join(DIST, 'theme.css'), theme())
declarations()
writeFileSync(join(DIST, 'host/components.d.ts'), globalComponents(HOST_EXPORTS.components))
cpSync(join(NUXT, 'ui'), join(DIST, 'ui'), { recursive: true })
rmSync(WORK, { recursive: true, force: true })

/** The module names the app shares, and the components `@interloper/host` exports by name. */
function host(): { modules: string[], components: string[] } {
    const source = readFileSync(HOST, 'utf8')
    const components = [...source.matchAll(/export \{ default as (\w+) \} from '[^']+\.vue'/g)].map(match => match[1]!)
    return { modules: Object.keys(SHARED_MODULES), components }
}

/**
 * `host/components.d.ts`: every component `@interloper/host` exports, declared global, so
 * an extension's templates type-check the components the Vite preset resolves for them.
 */
function globalComponents(names: string[]): string {
    const entry = relativeSpecifier(join(DIST, 'host/components.d.ts'), join(DIST, 'host', relative(APP, HOST)))
    const lines = names.map(name => `        ${name}: typeof import('${entry.replace(/\.ts$/, '')}')['${name}']`)
    return `export {}\ndeclare module 'vue' {\n    export interface GlobalComponents {\n${lines.join('\n')}\n    }\n}\n`
}

/**
 * The app's `@theme` blocks (Nuxt UI's, then the app's own), each to reference: an
 * extension's utilities resolve to the app's values and tokens, and its stylesheet
 * redefines no variable the app sets.
 */
function theme(): string {
    const blocks = [join(NUXT, 'ui.css'), join(APP, 'app/assets/css/main.css')]
        .flatMap(path => themeBlocks(readFileSync(path, 'utf8')))
    return `/* Generated by scripts/build.ts from the app's theme. */\n\n${
        blocks.map(body => `@theme reference inline {${body}}`).join('\n\n')}\n`
}

/** The body of every `@theme` block in a stylesheet. */
function themeBlocks(css: string): string[] {
    return [...css.matchAll(/@theme\b[^{]*\{/g)].map((match) => {
        const start = match.index + match[0].length
        let depth = 1
        let end = start
        while (depth) depth += { '{': 1, '}': -1 }[css[end++]!] ?? 0
        return css.slice(start, end - 1)
    })
}

/** Emit the declarations `@interloper/host` reaches into `dist/host/`. */
function declarations(): void {
    mkdirSync(WORK, { recursive: true })
    const tsconfig = join(WORK, 'tsconfig.json')
    writeFileSync(tsconfig, JSON.stringify({
        extends: join(NUXT, 'tsconfig.app.json'),
        compilerOptions: { noEmit: false, declaration: true, emitDeclarationOnly: true, outDir: OUT, rootDir: APP },
        files: [join(NUXT, 'nuxt.d.ts'), HOST],
    }))
    const vueTsc = createRequire(import.meta.url).resolve('vue-tsc/bin/vue-tsc.js')
    let report = ''
    try {
        execFileSync(process.execPath, [vueTsc, '-p', tsconfig], { cwd: WORK, encoding: 'utf8', stdio: 'pipe' })
    }
    catch (error) {
        report = (error as { stdout: string }).stdout
    }

    const globals = globalTypes()
    const reached = new Set<string>()
    const unresolved = new Set<string>()
    const queue = [emitted(HOST)]
    while (queue.length) {
        const file = queue.pop()!
        if (reached.has(file)) continue
        reached.add(file)
        const text = readFileSync(file, 'utf8')
        for (const [, , , specifier] of text.matchAll(SPECIFIER)) {
            const target = declarationOf(file, specifier!)
            if (target) queue.push(target)
            else if (specifier!.startsWith('#')) unresolved.add(specifier!)
        }
        for (const [, name] of text.matchAll(GLOBAL)) {
            const source = globals.get(name!)
            const target = source && isAbsolute(source) ? existingDeclaration(emittedPath(source)) : undefined
            if (target) queue.push(target)
        }
    }

    const failures = report.split('\n').filter((line) => {
        const path = line.match(/^(.+?)\(\d+,\d+\): error TS/)?.[1]
        return path !== undefined && reached.has(emitted(resolve(WORK, path)))
    })
    if (failures.length)
        throw new Error(`@interloper/host's declarations do not emit cleanly:\n${failures.join('\n')}`)
    if (unresolved.size)
        console.warn(`@interloper/host reaches Nuxt-internal modules, typed as any for extensions: ${[...unresolved].join(', ')}`)

    const target = (file: string) => join(DIST, 'host', relative(OUT, file))
    const inHost = (file: string, path: string) => relativeSpecifier(target(file), join(DIST, 'host', relative(APP, path)))
    for (const file of reached) {
        const text = readFileSync(file, 'utf8')
            .replace(SPECIFIER, (whole, lead: string, quote: string, specifier: string) => {
                const alias = aliased(specifier)
                return alias ? `${lead}${quote}${inHost(file, alias)}${quote}` : whole
            })
            .replace(GLOBAL, (whole, name: string) => {
                const source = globals.get(name)
                if (!source) return whole
                return `import('${isAbsolute(source) ? inHost(file, source) : source}').${name}`
            })
        mkdirSync(dirname(target(file)), { recursive: true })
        writeFileSync(target(file), text)
    }
}

/**
 * The types Nuxt's auto-imports make global in the app, which declarations name as
 * `globalThis.<name>`: name → package, or → the app file that exports it.
 */
function globalTypes(): Map<string, string> {
    const imports = readFileSync(join(NUXT, 'types/imports.d.ts'), 'utf8')
    const block = imports.slice(imports.indexOf('// for type re-export'))
    const globals = new Map<string, string>()
    for (const [, names, source] of block.matchAll(/export type \{([^}]*)\} from '([^']+)'/g)) {
        for (const name of names!.split(',').map(name => name.trim()).filter(Boolean))
            globals.set(name, source!.startsWith('.') ? resolve(NUXT, 'types', source!) : source!)
    }
    return globals
}

/** The emitted declaration of an app source file. */
function emitted(source: string): string {
    return join(OUT, relative(APP, source)).replace(/\.ts$/, '.d.ts').replace(/\.vue$/, '.vue.d.ts')
}

/** The emitted declaration a specifier in `from` names, or `undefined` for a package or a Nuxt-internal module. */
function declarationOf(from: string, specifier: string): string | undefined {
    const alias = aliased(specifier)
    if (alias) return existingDeclaration(emittedPath(alias))
    return specifier.startsWith('.') ? existingDeclaration(resolve(dirname(from), specifier)) : undefined
}

/** The emitted declaration a module path without its extension resolves to, as TypeScript resolves it. */
function existingDeclaration(path: string): string | undefined {
    return [path, `${path}.d.ts`, path.replace(/\.(ts|js|mjs)$/, '.d.ts'), join(path, 'index.d.ts')]
        .find(candidate => candidate.endsWith('.d.ts') && existsSync(candidate) && statSync(candidate).isFile())
}

/** A path in the app mapped into the emitted tree. */
function emittedPath(path: string): string {
    return join(OUT, relative(APP, path))
}

/** The app path an aliased specifier (`~/stores/user`) names, or `undefined` when it uses no alias. */
function aliased(specifier: string): string | undefined {
    const match = specifier.match(/^(~~|@@|~|@)\/(.*)$/)
    return match ? join(ALIASES.get(match[1]!)!, match[2]!) : undefined
}

/** The app's `~`, `@`, `~~` and `@@` aliases, from the tsconfig Nuxt generates. */
function aliases(): Map<string, string> {
    const { compilerOptions } = JSON.parse(readFileSync(join(NUXT, 'tsconfig.app.json'), 'utf8'))
    return new Map(['~', '@', '~~', '@@'].map(alias => [alias, resolve(NUXT, compilerOptions.paths[alias][0])]))
}

/** A relative import specifier from one file to another, without a declaration extension. */
function relativeSpecifier(from: string, to: string): string {
    const path = relative(dirname(from), to).replace(/\.d\.ts$/, '')
    return path.startsWith('.') ? path : `./${path}`
}
